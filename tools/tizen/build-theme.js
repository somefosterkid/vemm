"use strict";
// Copies every paint declaration of samsung/Vemm/css/style.css, with its selector and @media, into
// samsung/Vemm/js/theme-rules.js: the template js/theme.js resolves for the chosen theme (see that file).
// Run with --write after changing a colour in style.css; without it, the script fails when the file is stale.
var fs = require("fs");
var path = require("path");
var root = path.resolve(__dirname, "../..");
var theme = require(path.join(root, "samsung/Vemm/js/theme.js"));
var source = fs.readFileSync(path.join(root, "samsung/Vemm/css/style.css"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
// The properties that paint, plus every shorthand or longhand sharing a value with them. The template comes after
// style.css, so all of them must move together: then the cascade between them is the stylesheet's own.
var paint = /^(?:color|background(?:-[a-z-]+)?|border(?:-(?:top|right|bottom|left))?(?:-(?:color|style|width))?|border-image(?:-[a-z]+)?|outline(?:-(?:color|style|width))?|box-shadow|text-shadow|fill|stroke|-webkit-text-fill-color|caret-color)$/;

// Splits a declaration block on semicolons outside strings and brackets.
function declarations(block) {
    var list = [], current = "", quote = "", depth = 0;
    block.split("").forEach(function (character) {
        if (quote) { if (character === quote) { quote = ""; } }
        else if (character === "\"" || character === "'") { quote = character; }
        else if (character === "(") { depth += 1; }
        else if (character === ")") { depth -= 1; }
        else if (character === ";" && !depth) { list.push(current); current = ""; return; }
        current += character;
    });
    return list.concat(current).map(function (text) { return text.trim().replace(/\s+/g, " "); }).filter(Boolean);
}

// The paint rules of a run of rules, one per line; an @media block keeps its paint rules inside it.
function paintRules(text) {
    var lines = [];
    var at = 0;
    while (at < text.length) {
        var open = text.indexOf("{", at);
        if (open === -1) { break; }
        var prelude = text.slice(at, open).trim().replace(/\s+/g, " ");
        var depth = 1, close = open + 1;
        while (depth) {
            if (text[close] === "{") { depth += 1; }
            if (text[close] === "}") { depth -= 1; }
            close += 1;
        }
        var body = text.slice(open + 1, close - 1);
        if (/^@media/.test(prelude)) {
            var inner = paintRules(body);
            if (inner.length) { lines.push(prelude + "{"); lines = lines.concat(inner); lines.push("}"); }
        } else if (/^@/.test(prelude)) {
            if (body.indexOf("$") !== -1) { throw new Error("Theme tokens are not supported inside " + prelude); }
        } else {
            var painted = declarations(body).filter(function (declaration) {
                return paint.test(declaration.slice(0, declaration.indexOf(":")).trim());
            });
            if (painted.length) { lines.push(prelude + "{" + painted.join(";") + "}"); }
        }
        at = close;
    }
    return lines;
}

var rules = paintRules(source);
var roles = theme.roles();
rules.join("\n").replace(/\$([a-z][a-z0-9-]*)/g, function (match, name) {
    if (roles.indexOf(name) === -1) { throw new Error("style.css names an unknown theme token: " + match); }
    return match;
});
var output = "// Generated by tools/tizen/build-theme.js from css/style.css: its paint declarations, whose $tokens js/theme.js\n" +
    "// resolves for the chosen theme. Do not edit; change style.css and run node tools/tizen/build-theme.js --write.\n" +
    "(function (root, rules) {\n" +
    "    if (typeof module === \"object\" && module.exports) { module.exports = rules; } else { root.VemmThemeRules = rules; }\n" +
    "}(this, [\n" + rules.map(function (rule) { return "    " + JSON.stringify(rule); }).join(",\n") + "\n].join(\"\\n\")));\n";
var target = path.join(root, "samsung/Vemm/js/theme-rules.js");
if (process.argv[2] === "--write") { fs.writeFileSync(target, output); }
else if (!fs.existsSync(target) || fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== output) {
    throw new Error("Theme rules are stale. Run node tools/tizen/build-theme.js --write.");
}
